// Writes src/migrations.generated.ts from migrations/*.sql and
// migrations-control/*.sql. The serverless function bundle only carries code,
// not loose .sql files, and hosted mode runs migrations at request time (each
// new workspace builds its own schema), so the SQL ships inside the code.
// Run after changing any migration: `bun run embed:migrations`. A test fails
// if this file is out of date.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");

export function readMigrations(dir: string): Array<{ name: string; sql: string }> {
  return readdirSync(join(root, dir))
    .filter((f) => f.endsWith(".sql"))
    .sort()
    .map((name) => ({ name, sql: readFileSync(join(root, dir, name), "utf8") }));
}

export function render(): string {
  const block = (list: Array<{ name: string; sql: string }>) =>
    `[\n${list.map((m) => `  { name: ${JSON.stringify(m.name)}, sql: ${JSON.stringify(m.sql)} },`).join("\n")}\n]`;
  return `// GENERATED by scripts/embed-migrations.ts from migrations/ and migrations-control/. Do not edit.
export const APP_MIGRATIONS: ReadonlyArray<{ name: string; sql: string }> = ${block(readMigrations("migrations"))};

export const CONTROL_MIGRATIONS: ReadonlyArray<{ name: string; sql: string }> = ${block(readMigrations("migrations-control"))};
`;
}

if (import.meta.main) {
  writeFileSync(join(root, "src", "migrations.generated.ts"), render());
  console.log("wrote src/migrations.generated.ts");
}
